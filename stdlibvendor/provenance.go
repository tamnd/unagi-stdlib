package stdlibvendor

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

// ToolVersion is stamped into PROVENANCE.toml by a sync run.
const ToolVersion = "unagi-vendor 0.1.0"

// LoadProvenance parses PROVENANCE.toml for the upstream pin and the scope
// rules. It reads only the subset of TOML the pin file uses: [section] headers,
// key = "string", and key = ["a", "b"] arrays that may span lines. Keeping the
// parser tiny avoids a third-party TOML dependency leaking into unagi's build.
func LoadProvenance(pathIn string) (*Provenance, error) {
	f, err := os.Open(pathIn)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()

	p := &Provenance{}
	section := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = strings.Trim(line, "[]")
			continue
		}
		key, rest, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key = strings.TrimSpace(key)
		rest = strings.TrimSpace(rest)

		if strings.HasPrefix(rest, "[") {
			// Array value, possibly spanning multiple lines until the closing ].
			for !strings.Contains(rest, "]") && sc.Scan() {
				rest += " " + strings.TrimSpace(sc.Text())
			}
			vals := parseStringArray(rest)
			if section == "scope" {
				switch key {
				case "exclude_dirs":
					p.Scope.ExcludeDirs = vals
				case "exclude_files":
					p.Scope.ExcludeFiles = vals
				case "include_only_suffix":
					p.Scope.IncludeSuffix = vals
				}
			}
			continue
		}

		val := unquote(stripInlineComment(rest))
		if section == "upstream" {
			switch key {
			case "tag":
				p.Tag = val
			case "commit":
				p.Commit = val
			case "subtree":
				p.Subtree = val
			}
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if p.Tag == "" || p.Commit == "" {
		return nil, fmt.Errorf("PROVENANCE.toml: missing upstream tag or commit")
	}
	if len(p.Scope.IncludeSuffix) == 0 {
		return nil, fmt.Errorf("PROVENANCE.toml: scope.include_only_suffix is empty")
	}
	return p, nil
}

// EmitProvenance renders PROVENANCE.toml deterministically from the pin, the
// scope, and a sync run's results. Re-running sync at the same tag reproduces
// this byte-for-byte except for generated_at, which is the only time-varying
// field on purpose.
func EmitProvenance(p *Provenance, files, lines int, generatedAt string) string {
	var b strings.Builder
	b.WriteString("# Generated by cmd/unagi-vendor. The [upstream] and [scope] blocks are the\n")
	b.WriteString("# inputs a reviewer edits to bump or re-scope; [result] is written by a sync run.\n\n")

	b.WriteString("[upstream]\n")
	fmt.Fprintf(&b, "project = %q\n", "cpython")
	fmt.Fprintf(&b, "tag = %q\n", p.Tag)
	fmt.Fprintf(&b, "commit = %q\n", p.Commit)
	fmt.Fprintf(&b, "subtree = %q\n\n", p.Subtree)

	b.WriteString("[scope]\n")
	writeArray(&b, "exclude_dirs", p.Scope.ExcludeDirs)
	writeArray(&b, "exclude_files", p.Scope.ExcludeFiles)
	writeArray(&b, "include_only_suffix", p.Scope.IncludeSuffix)
	b.WriteString("\n")

	b.WriteString("[result]\n")
	fmt.Fprintf(&b, "files = %d\n", files)
	fmt.Fprintf(&b, "lines = %d\n", lines)
	fmt.Fprintf(&b, "generated_at = %q\n", generatedAt)
	fmt.Fprintf(&b, "tool_version = %q\n", ToolVersion)
	return b.String()
}

func writeArray(b *strings.Builder, key string, vals []string) {
	if len(vals) == 0 {
		fmt.Fprintf(b, "%s = []\n", key)
		return
	}
	fmt.Fprintf(b, "%s = [\n", key)
	for _, v := range vals {
		fmt.Fprintf(b, "  %q,\n", v)
	}
	b.WriteString("]\n")
}

func parseStringArray(s string) []string {
	open := strings.Index(s, "[")
	close := strings.LastIndex(s, "]")
	if open < 0 || close < 0 || close < open {
		return nil
	}
	inner := s[open+1 : close]
	var out []string
	for part := range strings.SplitSeq(inner, ",") {
		v := unquote(stripInlineComment(strings.TrimSpace(part)))
		if v != "" {
			out = append(out, v)
		}
	}
	return out
}

func stripInlineComment(s string) string {
	// Drop a trailing # comment that sits outside a quoted string.
	inQuote := false
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '"':
			inQuote = !inQuote
		case '#':
			if !inQuote {
				return strings.TrimSpace(s[:i])
			}
		}
	}
	return s
}

func unquote(s string) string {
	s = strings.TrimSpace(s)
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		return s[1 : len(s)-1]
	}
	return s
}
